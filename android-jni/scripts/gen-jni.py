"""Generate typed forwarding, not libc emulation. JNI1.6 plus GetModule."""

import argparse
import json
import re
from pathlib import Path

root = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument(
    "--jni-header",
    type=Path,
    default=root / "build/jni-include/jni.h",
)
parser.add_argument("--output", type=Path, default=root / "build/generated")
options = parser.parse_args()
s = (
    options.jni_header.read_text()
    .split("struct JNINativeInterface {")[1]
    .split("\n};")[0]
)
s = re.sub(r"/\*.*?\*/", "", s, flags=re.DOTALL)
api = []
for ret, name, args in re.findall(
    r"([\w\s*]+)\(\*(\w+)\)\((.*?)\);", s, flags=re.DOTALL
):
    norm = lambda t: re.sub(r"\s*\*\s*", "*", " ".join(t.split()))
    api.append((norm(ret), name, [norm(x) for x in args.split(",")][1:]))
assert len(api) == 229
api.append(("jobject", "GetModule", ["jclass"]))
refs = {
    "jobject",
    "jclass",
    "jstring",
    "jthrowable",
    "jarray",
    "jweak",
    "jobjectArray",
    *[
        f"j{t}Array"
        for t in [
            "boolean",
            "byte",
            "char",
            "short",
            "int",
            "long",
            "float",
            "double",
        ]
    ],
}
fields = {
    "jboolean": "z",
    "jbyte": "b",
    "jchar": "c",
    "jshort": "s",
    "jint": "i",
    "jsize": "i",
    "jlong": "j",
    "jfloat": "f",
    "jdouble": "d",
    "jobjectRefType": "i",
}
field = lambda t: fields.get(t, "l")
g = ["/* Generated by android-jni/scripts/gen-jni.py. */"]
h = ["/* Generated by android-jni/scripts/gen-jni.py. */", "switch(r->api) {"]
for i, (ret, name, ts) in enumerate(api):
    params = ["JNIEnv *env"] + [
        f"{t} a{k + 1}" if t != "..." else "..." for k, t in enumerate(ts)
    ]
    g.append(f"static {ret} fg_{name}(" + ",".join(params) + ") {")
    if name == "GetJavaVM":
        g.append(
            f" if(a1){{*a1=NULL;}} if (!fg_valid(env)) {{ return JNI_ERR; }} atomic_fetch_add(&G->hits[{i}],1); if (!a1) {{ return JNI_ERR; }} *a1=&fg_vm; return JNI_OK; }}"
        )
        h.append(f"case {i}: r->error=1; break;")
        continue
    g.append(" jvalue a[8]={0};")
    for k, t in enumerate(ts):
        if t == "...":
            g.append(f" va_list va; va_start(va,a{k}); a[{k}].l=(jobject)&va;")
        elif t == "va_list":
            g.append(
                f" va_list va; va_copy(va,a{k + 1}); a[{k}].l=(jobject)&va;"
            )
        else:
            g.append(
                f" a[{k}].{field(t)}=({'jobject' if field(t) == 'l' else t})a{k + 1};"
            )
    g.append(f" jvalue result=fg_rpc(env,{i},a);")
    if any(t in ("...", "va_list") for t in ts):
        g.append(" va_end(va);")
    if ret != "void":
        g.append(f" return ({ret})result.{field(ret)};")
    else:
        g.append(" (void)result;")
    g.append("}")
    h.append(f"case {i}: {{ /* {name} */")
    if name == "GetVersion":
        h.append(" r->result.i=gw_host_jni_version; break; }")
        continue
    if name == "GetModule":
        h.extend(
            [
                " if(gw_host_jni_version<0x00090000){",
                '  jclass unsupported=(*env)->FindClass(env,"java/lang/UnsupportedOperationException");',
                '  if(unsupported){(*env)->ThrowNew(env,unsupported,"Host VM does not expose JNI GetModule");(*env)->DeleteLocalRef(env,unsupported);}',
                "  break; }",
                " jclass rpc_arg0=(jclass)fh_ref(c,r->a[0].l);",
                " if(c->marshal_error){r->error=2;break;}",
                f" GW_RPC_SCOPE(jni,GW_RPC_HOST_JNI_EXECUTE,{i});",
                " jobject value=((jobject (*)(JNIEnv*,jclass))((void **)*env)[233])(env,rpc_arg0);",
                " GW_RPC_SCOPE_END(jni);",
                " reference_result(call,value,H_LOCAL); break; }",
            ]
        )
        continue
    if name == "UnregisterNatives":
        h.append(
            " jclass cls=(jclass)fh_ref(c,r->a[0].l);\n"
            " if(c->marshal_error){r->error=2;break;}\n"
            f" GW_RPC_SCOPE(jni,GW_RPC_HOST_JNI_EXECUTE,{i});\n"
            " r->result.i=fh_unregister(c,cls);\n"
            " GW_RPC_SCOPE_END(jni); break; }"
        )
        continue
    if name == "RegisterNatives":
        h.append(
            " jclass cls=(jclass)fh_ref(c,r->a[0].l);\n"
            " if(c->marshal_error){r->error=2;break;}\n"
            f" GW_RPC_SCOPE(jni,GW_RPC_HOST_JNI_EXECUTE,{i});\n"
            " r->result.i=fh_register(c,cls,(const JNINativeMethod*)r->a[1].l,r->a[2].i);\n"
            " GW_RPC_SCOPE_END(jni); break; }"
        )
        continue
    vals = []
    for k, t in enumerate(ts):
        if t in refs:
            v = f"({t})fh_ref(c,r->a[{k}].l)"
        elif t == "jmethodID":
            v = f"(jmethodID)fh_id(c,r->a[{k}].l,H_METHOD)"
        elif t == "jfieldID":
            v = f"(jfieldID)fh_id(c,r->a[{k}].l,H_FIELD)"
        else:
            v = f"({t})r->a[{k}].{field(t)}"
        vals.append(v)
    callname = name
    if name.startswith(("Call", "NewObject")) and "jmethodID" in ts:
        method = ts.index("jmethodID")
        arg = len(ts) - 1
        mode = "A" if name.endswith("A") else "V"
        h.append(
            f" jvalue values[FB_ARGS]; if (!fh_decode(c,r->a[{method}].l,r->a[{arg}].l,'{mode}',values)) {{ r->error=2;break; }}"
        )
        vals[-1] = "values"
        callname = name[:-1] + "A" if name.endswith(("A", "V")) else name + "A"
    array_elements = re.fullmatch(
        r"(Get|Release)(Boolean|Byte|Char|Short|Int|Long|Float|Double)ArrayElements",
        callname,
    )
    callee = (
        f"fh_{array_elements[1].lower()}_{array_elements[2].lower()}_elements"
        if array_elements
        else f"(*env)->{callname}"
    )
    # Resolve every token before invoking JNI, so a failed lookup cannot call
    # the VM with NULL arguments or a newly pending marshalling exception.
    resolved = list(vals)
    for k, t in enumerate(ts):
        if t in refs or t in ("jmethodID", "jfieldID"):
            h.append(f" {t} rpc_arg{k}={vals[k]};")
            resolved[k] = f"rpc_arg{k}"
    h.append(" if(c->marshal_error){r->error=2;break;}")
    discard = {
        "GetStringChars": "discard_chars",
        "GetStringUTFChars": "discard_utf_chars",
        "GetStringCritical": "discard_string_critical",
        "GetPrimitiveArrayCritical": "discard_array_critical",
    }.get(name)
    if array_elements and array_elements[1] == "Get":
        discard = f"discard_{array_elements[2].lower()}_elements"
    if discard:
        h.append(" jboolean copy=JNI_FALSE;")
        resolved[1] = "r->a[1].l ? &copy : NULL"
    measured = (
        f"{callee}(env" + (" ," + ",".join(resolved) if resolved else "") + ")"
    )
    h.append(f" GW_RPC_SCOPE(jni,GW_RPC_HOST_JNI_EXECUTE,{i});")
    h.append(
        " " + measured + ";" if ret == "void" else f" {ret} value={measured};"
    )
    h.append(" GW_RPC_SCOPE_END(jni);")
    if name == "PopLocalFrame":
        h.append(" fh_drop_locals(c,c->local_depth); c->local_depth--;")
    if name in ("DeleteLocalRef", "DeleteGlobalRef", "DeleteWeakGlobalRef"):
        h.append(" fh_drop_token(r->a[0].l);")
    if name == "ReleaseStringCritical":
        h.append(" if(c->critical)c->critical--;")
    if name == "ReleasePrimitiveArrayCritical":
        h.append(" if(c->critical)c->critical--;")
    if discard:
        h.append(
            f" pointer_result(call,rpc_arg0,value,{discard},copy,{int(name.endswith('Critical'))});"
        )
    elif name == "PushLocalFrame":
        h.append(" push_frame_result(call,value);")
    elif name == "MonitorEnter":
        h.append(" monitor_enter_result(call,rpc_arg0,value);")
    elif ret in refs:
        kind = {"NewGlobalRef": "H_GLOBAL", "NewWeakGlobalRef": "H_WEAK"}.get(
            name, "H_LOCAL"
        )
        h.append(f" reference_result(call,(jobject)value,{kind});")
    elif ret in ("jmethodID", "jfieldID"):
        kind = "H_METHOD" if ret == "jmethodID" else "H_FIELD"
        sig = "(const char*)r->a[2].l" if "const char*" in ts else "NULL"
        if name.startswith("FromReflected"):
            h.extend(
                [
                    " if(value){",
                    "  char sig[FB_SIG];",
                    '  snprintf(sig,sizeof sig,"%s",fh_describe(c,rpc_arg0));',
                    "  if((*env)->ExceptionCheck(env))break;",
                    "  jclass owner=fh_declaring_class(c,rpc_arg0);",
                    f"  id_result(call,(void*)value,{kind},sig,NULL,owner);",
                    " }",
                ]
            )
        else:
            reflected = (
                "ToReflectedMethod"
                if ret == "jmethodID"
                else "ToReflectedField"
            )
            static = "JNI_TRUE" if name.startswith("GetStatic") else "JNI_FALSE"
            h.extend(
                [
                    " if(value){",
                    f"  jobject member=(*env)->{reflected}(env,rpc_arg0,value,{static});",
                    "  if((*env)->ExceptionCheck(env)){discard_local(c,NULL,member);break;}",
                    "  jclass owner=fh_declaring_class(c,member);",
                    f"  id_result(call,(void*)value,{kind},{sig},member,owner);",
                    " }",
                ]
            )
    elif ret != "void":
        h.append(
            f" r->result.{field(ret)}=({'jobject' if field(ret) == 'l' else ret})value;"
        )
    h.append(" break; }")
h.append("default:r->error=3;break; }")
g.append("static const struct fg_extended_table fg_table={ .base={")
for ret, name, ts in api[:-1]:
    g.append(f" .{name}=fg_{name},")
g.append("},.GetModule=fg_GetModule};")
status_names = {
    "Throw",
    "ThrowNew",
    "PushLocalFrame",
    "EnsureLocalCapacity",
    "RegisterNatives",
    "UnregisterNatives",
    "MonitorEnter",
    "MonitorExit",
    "GetJavaVM",
}
emergency_names = {
    "ExceptionOccurred",
    "ExceptionDescribe",
    "ExceptionClear",
    "ExceptionCheck",
    "DeleteLocalRef",
    "DeleteGlobalRef",
    "DeleteWeakGlobalRef",
    "ReleaseStringChars",
    "ReleaseStringUTFChars",
    "ReleaseStringCritical",
    "ReleasePrimitiveArrayCritical",
    "MonitorExit",
}
emergency_names.update(
    "Release" + t + "ArrayElements"
    for t in (
        "Boolean",
        "Byte",
        "Char",
        "Short",
        "Int",
        "Long",
        "Float",
        "Double",
    )
)
policy = [
    "/* Generated failure and emergency policy. */",
    "static inline jvalue fg_failure_result(int api) {",
    " jvalue result={0}; switch(api) {",
]
policy += [
    f" case {i}:" for i, (_, name, _) in enumerate(api) if name in status_names
]
policy += [
    " result.i=JNI_ERR; break; default: break; } return result; }",
    "static inline int fg_emergency_api(int api) { switch(api) {",
]
policy += [
    f" case {i}:"
    for i, (_, name, _) in enumerate(api)
    if name in emergency_names
]
policy += [" return 1; default: return 0; }}"]
out = options.output
out.mkdir(parents=True, exist_ok=True)
(out / "guest-policy.inc").write_text("\n".join(policy) + "\n")
(out / "guest-jni.inc").write_text("\n".join(g) + "\n")
(out / "host-jni.inc").write_text("\n".join(h) + "\n")
names = [x[1] for x in api] + [
    "VM.DestroyJavaVM",
    "VM.AttachCurrentThread",
    "VM.DetachCurrentThread",
    "VM.GetEnv",
    "VM.AttachCurrentThreadAsDaemon",
]
(out / "api-names.inc").write_text(
    ",\n".join(json.dumps(x) for x in names) + "\n"
)
(out / "jni-api-inventory.json").write_text(
    json.dumps(
        [
            {"index": i, "name": n, "status": "NOT_RUN"}
            for i, n in enumerate(names)
        ],
        indent=2,
    )
    + "\n"
)
print("Generated", len(api), "JNI methods and 5 VM API inventory entries")
